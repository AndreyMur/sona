/// Приводит текст к нижнему регистру, заменяет «ё» и срезает пунктуацию.
String normalizeSonaText(String input) {
  return input
      .toLowerCase()
      .replaceAll('ё', 'е')
      .replaceAll(RegExp(r'[^\p{L}\p{N}\s]+', unicode: true), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
}

/// Отсекает конечные гласные/мягкий знак для устойчивости к падежам.
String _stem(String word) {
  var result = word;
  while (result.isNotEmpty && 'аеиоуыэюяьй'.contains(result[result.length - 1])) {
    result = result.substring(0, result.length - 1);
  }
  return result;
}

/// Ищет категорийное слово по основе.
///
/// Сначала точное совпадение основ, затем самая длинная основа, с которой
/// начинается слово (или которая начинается со слова).
CategoryWord? lookupCategoryWord(String normalizedWord) {
  if (normalizedWord.isEmpty) return null;

  final exact = kCategoryWords[normalizedWord];
  if (exact != null) return exact;

  final wordStem = _stem(normalizedWord);
  if (wordStem.isEmpty) return null;

  String? bestKey;
  CategoryWord? bestWord;
  for (final entry in kCategoryWords.entries) {
    final keyStem = _stem(entry.key);
    if (keyStem.isEmpty) continue;
    if (keyStem == wordStem) return entry.value;
    if (keyStem.length < 3) continue;
    final matches =
        wordStem.startsWith(keyStem) ||
        (wordStem.length >= 3 && keyStem.startsWith(wordStem));
    if (matches && (bestKey == null || keyStem.length > bestKey.length)) {
      bestKey = keyStem;
      bestWord = entry.value;
    }
  }
  return bestWord;
}

/// Ищет первое категорийное слово в тексте в порядке появления.
CategoryWord? findCategoryInText(String normalizedText) {
  for (final word in normalizedText.split(' ')) {
    final match = lookupCategoryWord(word);
    if (match != null) return match;
  }
  return null;
}
