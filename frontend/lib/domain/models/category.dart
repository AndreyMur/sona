/// Категория операции с подкатегориями.
@immutable
class Category {
  const Category({
    required this.id,
    required this.name,
    required this.isIncome,
    required this.subcategories,
    this.sortOrder = 0,
  });

  final int id;
  final String name;
  final bool isIncome;
  final List<String> subcategories;
  final int sortOrder;
}

